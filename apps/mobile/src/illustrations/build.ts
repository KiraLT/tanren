/**
 * Pure build: batches of scenes → the committed outputs (SVG files and generated TS modules) and
 * the reviewer contact sheet. `scripts/illustrations.ts` only reads scene modules and writes files.
 */
import type { CatalogExercise, MuscleGroup } from "@tanren/shared"
import { Option } from "effect"
import { renderScene, type Scene } from "./compose"

export interface Batch {
  /** File name without extension, `b00` … `bNN`. */
  readonly name: string
  readonly scenes: ReadonlyArray<Scene>
}

/** A file relative to `apps/mobile`. */
export interface OutputFile {
  readonly path: string
  readonly content: string
}

export interface Rendered {
  readonly id: string
  readonly batch: string
  readonly muscle: Option.Option<MuscleGroup>
  readonly svg: string
}

export const SVG_DIR = "assets/exercises"
export const GENERATED_DIR = "src/illustrations/generated"
export const CONTACT_SHEET = `${SVG_DIR}/_contact-sheet.html`

const BATCH_FILE = /^b\d{2,}\.ts$/

/** Scene modules the build picks up: `scenes/b00.ts`, `scenes/b01.ts`, … (tests excluded). */
export const isBatchFile = (fileName: string): boolean => BATCH_FILE.test(fileName)

/** The catalog's first primary muscle for an illustration id (TI2). */
export const muscleFor = (
  catalog: ReadonlyArray<CatalogExercise>,
  id: string,
): Option.Option<MuscleGroup> =>
  Option.fromNullishOr(catalog.find((entry) => entry.illustrationId === id)).pipe(
    Option.flatMap((entry) => Option.fromNullishOr(entry.primaryMuscles[0])),
  )

export const renderBatches = (
  batches: ReadonlyArray<Batch>,
  catalog: ReadonlyArray<CatalogExercise>,
): ReadonlyArray<Rendered> =>
  batches.flatMap((batch) =>
    batch.scenes.map((scene) => {
      const muscle = muscleFor(catalog, scene.id)
      return {
        id: scene.id,
        batch: batch.name,
        muscle,
        svg: renderScene(scene, Option.getOrUndefined(muscle)),
      }
    }),
  )

const HEADER = "// Generated by `pnpm -F @tanren/mobile illustrations:build`. Do not edit."

const IDENTIFIER = /^[A-Za-z_$][\w$]*$/

/** One object entry in Biome's output shape: bare identifier keys, break after `:` past width 100. */
const entry = (key: string, svg: string): string => {
  const name = IDENTIFIER.test(key) ? key : `"${key}"`
  // SVGs only contain double quotes, so Biome keeps them in a single-quoted literal.
  const value = `'${svg}'`
  const oneLine = `  ${name}: ${value},`
  return oneLine.length <= 100 ? oneLine : `  ${name}:\n    ${value},`
}

export const batchModule = (name: string, rendered: ReadonlyArray<Rendered>): string =>
  [
    HEADER,
    `export const ${name}: Readonly<Record<string, string>> = {`,
    ...rendered.map((r) => entry(r.id, r.svg)),
    "}",
    "",
  ].join("\n")

export const indexModule = (batchNames: ReadonlyArray<string>): string =>
  [
    HEADER,
    'import type { IllustrationId } from "@tanren/shared"',
    ...batchNames.map((name) => `import { ${name} } from "./${name}"`),
    "",
    "/** Every drawn illustration by id; ids not drawn yet are absent (the UI shows a placeholder). */",
    "export const ILLUSTRATIONS: Readonly<Record<IllustrationId, string>> = {",
    ...batchNames.map((name) => `  ...${name},`),
    "}",
    "",
  ].join("\n")

/** Every committed output: one SVG per scene, one TS module per batch, and the index. */
export const buildOutputs = (
  batches: ReadonlyArray<Batch>,
  catalog: ReadonlyArray<CatalogExercise>,
): ReadonlyArray<OutputFile> => {
  const rendered = renderBatches(batches, catalog)
  const svgs = rendered.map((r) => ({ path: `${SVG_DIR}/${r.id}.svg`, content: r.svg }))
  const modules = batches.map((batch) => ({
    path: `${GENERATED_DIR}/${batch.name}.ts`,
    content: batchModule(
      batch.name,
      rendered.filter((r) => r.batch === batch.name),
    ),
  }))
  const index = {
    path: `${GENERATED_DIR}/index.ts`,
    content: indexModule(batches.map((batch) => batch.name)),
  }
  return [...svgs, ...modules, index]
}

const tile = (r: Rendered, size: number) =>
  `<div class="tile" style="width:${size}px;height:${size}px">${r.svg}</div>`

/** Every SVG at 160 and 48 px on a light and a dark card, labelled id · batch · muscle. */
export const contactSheet = (rendered: ReadonlyArray<Rendered>): string => {
  const cards = rendered
    .map((r) => {
      const label = `${r.id} · ${r.batch} · ${Option.getOrElse(r.muscle, () => "no catalog entry")}`
      const row = `${tile(r, 160)}${tile(r, 48)}`
      return `<figure><div class="pair"><div class="light">${row}</div><div class="dark">${row}</div></div><figcaption>${label}</figcaption></figure>`
    })
    .join("\n")
  return `<!doctype html>
<html lang="en"><head><meta charset="utf-8"><title>Illustrations contact sheet</title>
<style>
body{font:13px system-ui,sans-serif;margin:16px;background:#f4f4f5;color:#18181b}
main{display:flex;flex-wrap:wrap;gap:16px}
figure{margin:0;background:#fff;border-radius:8px;padding:8px}
.pair{display:flex;gap:8px}.light,.dark{display:flex;gap:8px;align-items:flex-end;padding:8px;border-radius:6px}
.light{background:#ffffff;border:1px solid #e4e4e7}.dark{background:#18181b}
.tile svg{width:100%;height:100%}
figcaption{margin-top:6px}
</style></head><body><h1>Illustrations (${rendered.length})</h1><main>
${cards}
</main></body></html>
`
}
